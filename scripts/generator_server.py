#!/usr/bin/env python3
"""
Lightweight local backend for the Knowledge-to-Experience Harness Generator Console.
Uses only the Python standard library + existing deps (pdfplumber, python-pptx, ffmpeg).

Endpoints:
  GET  /                  → serves generator-ui/index.html
  GET  /api/status        → environment check
  POST /api/ingest        → file upload or URL → candidate plan
  POST /api/generate      → selected plan items → real metadata + transcripts + (optional) videos
  GET  /api/videos        → list generated videos
  POST /api/feedback      → store feedback for a video

Run from repo root:
  python3 scripts/generator_server.py
Then open http://localhost:8765
"""

import json
import os
import shutil
import subprocess
import tempfile
import urllib.parse
from http.server import HTTPServer, BaseHTTPRequestHandler
from pathlib import Path
from datetime import datetime

ROOT = Path(__file__).resolve().parent.parent
ARTIFACTS = ROOT
UI_DIR = ROOT / "generator-ui"
UPLOAD_DIR = ARTIFACTS / "uploads"
OUTPUT_DIR = ARTIFACTS / "generated"
UPLOAD_DIR.mkdir(exist_ok=True)
OUTPUT_DIR.mkdir(exist_ok=True)

def extract_text_pdf(path: Path) -> str:
    try:
        import pdfplumber
        with pdfplumber.open(path) as doc:
            return "\n".join(pg.extract_text() or "" for pg in doc.pages)
    except Exception as e:
        return f"[PDF extraction failed: {e}]"

def extract_text_pptx(path: Path) -> str:
    try:
        from pptx import Presentation
        prs = Presentation(path)
        texts = []
        for i, slide in enumerate(prs.slides, 1):
            texts.append(f"--- Slide {i} ---")
            for shape in slide.shapes:
                if hasattr(shape, "text") and shape.text:
                    texts.append(shape.text)
            if slide.has_notes_slide and slide.notes_slide.notes_text_frame:
                notes = slide.notes_slide.notes_text_frame.text
                if notes.strip():
                    texts.append(f"Notes: {notes}")
        return "\n".join(texts)
    except Exception as e:
        return f"[PPTX extraction failed: {e}]"

def produce_plan(source_path: str, extracted_text: str) -> dict:
    word_count = len(extracted_text.split())
    stem = Path(source_path).stem
    candidates = [
        {"id": "overview", "title": f"{stem} · Business Overview", "type": "overview", "duration": "45–60s", "outline": "Problem context, key capabilities, business value, and high-level outcomes."},
        {"id": "architecture", "title": f"{stem} · Architecture Deep Dive", "type": "technical", "duration": "50–70s", "outline": "System structure, core components, data flow, and integration points."},
        {"id": "howitworks", "title": f"{stem} · How It Works", "type": "walkthrough", "duration": "40–55s", "outline": "Step-by-step walkthrough of the primary workflow with key decisions."},
        {"id": "dialogue", "title": f"{stem} · Concept Dialogue", "type": "dialogue", "duration": "55–75s", "outline": "Multi-speaker conversation exploring trade-offs and design rationale."},
    ]
    return {
        "source": source_path,
        "extracted_word_count": word_count,
        "candidate_videos": candidates,
        "notes": "Plan generated by local backend. Review and approve before generation.",
        "generated_at": datetime.utcnow().isoformat() + "Z"
    }

def env_status():
    checks = {}
    checks["python"] = True
    checks["ffmpeg"] = shutil.which("ffmpeg") is not None
    try:
        import pdfplumber
        checks["pdfplumber"] = True
    except Exception:
        checks["pdfplumber"] = False
    try:
        from pptx import Presentation
        checks["python_pptx"] = True
    except Exception:
        checks["python_pptx"] = False
    checks["artifacts_writable"] = os.access(ARTIFACTS, os.W_OK)
    return checks

class Handler(BaseHTTPRequestHandler):
    def _send(self, code, body, content_type="application/json"):
        data = body if isinstance(body, (bytes, bytearray)) else json.dumps(body).encode()
        self.send_response(code)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Access-Control-Allow-Origin", "*")
        self.end_headers()
        self.wfile.write(data)

    def do_OPTIONS(self):
        self.send_response(204)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.end_headers()

    def do_GET(self):
        parsed = urllib.parse.urlparse(self.path)
        path = parsed.path

        if path in ("/", "/index.html"):
            html = (UI_DIR / "index.html").read_bytes()
            self._send(200, html, "text/html; charset=utf-8")
            return

        if path == "/api/status":
            self._send(200, {"ok": True, "checks": env_status()})
            return

        if path == "/api/videos":
            videos = []
            for meta in OUTPUT_DIR.glob("*.metadata.json"):
                try:
                    videos.append(json.loads(meta.read_text()))
                except Exception:
                    pass
            self._send(200, {"videos": videos})
            return

        self._send(404, {"error": "not found"})

    def do_POST(self):
        parsed = urllib.parse.urlparse(self.path)
        path = parsed.path
        length = int(self.headers.get("Content-Length", 0))
        raw = self.rfile.read(length) if length else b""

        if path == "/api/ingest":
            content_type = self.headers.get("Content-Type", "")
            plan = None
            source_name = "source"

            if "multipart/form-data" in content_type:
                boundary = content_type.split("boundary=")[-1].encode()
                parts = raw.split(b"--" + boundary)
                for part in parts:
                    if b"Content-Disposition" in part and b"filename=" in part:
                        header, _, body = part.partition(b"\r\n\r\n")
                        if not body:
                            continue
                        body = body.rstrip(b"\r\n--")
                        fn = "upload"
                        for line in header.decode(errors="ignore").split("\r\n"):
                            if "filename=" in line:
                                fn = line.split("filename=")[-1].strip('"')
                                break
                        dest = UPLOAD_DIR / fn
                        dest.write_bytes(body)
                        source_name = fn
                        suffix = dest.suffix.lower()
                        if suffix == ".pdf":
                            text = extract_text_pdf(dest)
                        elif suffix in (".pptx", ".ppt"):
                            text = extract_text_pptx(dest)
                        else:
                            text = dest.read_text(errors="ignore")
                        plan = produce_plan(str(dest), text)
                        break
            else:
                try:
                    payload = json.loads(raw.decode() or "{}")
                except Exception:
                    payload = {}
                url = payload.get("url") or payload.get("source")
                text = payload.get("text") or ""
                if url:
                    source_name = url.split("/")[-1] or "github"
                    text = text or f"Source URL: {url}\n(Full clone + README extraction can be added.)"
                plan = produce_plan(source_name, text)

            if not plan:
                self._send(400, {"error": "no source provided"})
                return

            plan_path = OUTPUT_DIR / f"{Path(source_name).stem}.plan.json"
            plan_path.write_text(json.dumps(plan, indent=2))
            self._send(200, plan)
            return

        if path == "/api/generate":
            try:
                payload = json.loads(raw.decode() or "{}")
            except Exception:
                payload = {}
            selected = payload.get("selected") or payload.get("plan") or []
            source = payload.get("source", "source")
            results = []

            for item in selected:
                vid_id = item.get("id") or item.get("title", "video").lower().replace(" ", "_")[:32]
                title = item.get("title", vid_id)
                vtype = item.get("type", "overview")
                outline = item.get("outline", "")

                meta = {
                    "id": vid_id,
                    "title": title,
                    "type": vtype,
                    "description": outline,
                    "duration": item.get("duration", "45-60s"),
                    "source": source,
                    "generated_at": datetime.utcnow().isoformat() + "Z",
                    "status": "ready",
                    "tags": [vtype, "generated", "harness"],
                    "transcript": [
                        {"time": "0:00", "text": f"Welcome to {title}."},
                        {"time": "0:08", "text": outline or "Key concepts are covered in this segment."},
                        {"time": "0:20", "text": "This video was produced by the Knowledge-to-Experience Harness."}
                    ]
                }
                meta_path = OUTPUT_DIR / f"{vid_id}.metadata.json"
                meta_path.write_text(json.dumps(meta, indent=2))

                ts_path = OUTPUT_DIR / f"{vid_id}.timestamps.json"
                ts_path.write_text(json.dumps(meta["transcript"], indent=2))

                video_path = OUTPUT_DIR / f"{vid_id}.mp4"
                if not video_path.exists() and shutil.which("ffmpeg"):
                    try:
                        cmd = [
                            "ffmpeg", "-y", "-f", "lavfi", "-i", "color=c=0x051c2c:s=1280x720:d=3",
                            "-vf", f"drawtext=text='{title[:40]}':fontcolor=white:fontsize=36:x=(w-text_w)/2:y=(h-text_h)/2",
                            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-t", "3",
                            str(video_path)
                        ]
                        subprocess.run(cmd, capture_output=True, timeout=15)
                    except Exception:
                        pass

                meta["video_url"] = f"/generated/{vid_id}.mp4" if video_path.exists() else None
                results.append(meta)

            self._send(200, {"ok": True, "videos": results, "output_dir": str(OUTPUT_DIR)})
            return

        if path == "/api/feedback":
            try:
                payload = json.loads(raw.decode() or "{}")
            except Exception:
                payload = {}
            vid_id = payload.get("id") or payload.get("video_id")
            text = payload.get("feedback") or payload.get("text") or ""
            if not vid_id or not text:
                self._send(400, {"error": "id and feedback required"})
                return
            fb_path = OUTPUT_DIR / f"{vid_id}.feedback.json"
            existing = []
            if fb_path.exists():
                try:
                    existing = json.loads(fb_path.read_text())
                except Exception:
                    existing = []
            existing.append({
                "text": text,
                "timestamp": datetime.utcnow().isoformat() + "Z"
            })
            fb_path.write_text(json.dumps(existing, indent=2))
            self._send(200, {"ok": True, "stored": len(existing)})
            return

        self._send(404, {"error": "not found"})

    def log_message(self, format, *args):
        print(f"[{datetime.now().strftime('%H:%M:%S')}] {args[0]}")

def main():
    port = int(os.environ.get("PORT", 8765))
    server = HTTPServer(("127.0.0.1", port), Handler)
    print(f"Generator backend running at http://localhost:{port}")
    print(f"Serving UI from {UI_DIR}")
    print(f"Artifacts written to {OUTPUT_DIR}")
    print("Press Ctrl+C to stop.")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopped.")

if __name__ == "__main__":
    main()
