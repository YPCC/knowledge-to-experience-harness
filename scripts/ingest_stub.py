#!/usr/bin/env python3
"""
Small ingestion stub for the Knowledge-to-Experience Harness.
Accepts a PPTX or PDF and produces a candidate-video plan (JSON).
"""

import json
import sys
from pathlib import Path

def extract_text_pdf(path: Path) -> str:
    try:
        import pdfplumber
        with pdfplumber.open(path) as doc:
            return "\n".join(pg.extract_text() or "" for pg in doc.pages)
    except Exception as e:
        return f"[PDF extraction failed: {e}]"

def extract_text_pptx(path: Path) -> str:
    try:
        from pptx import Presentation
        prs = Presentation(path)
        texts = []
        for i, slide in enumerate(prs.slides, 1):
            texts.append(f"--- Slide {i} ---")
            for shape in slide.shapes:
                if hasattr(shape, "text") and shape.text:
                    texts.append(shape.text)
            if slide.has_notes_slide and slide.notes_slide.notes_text_frame:
                notes = slide.notes_slide.notes_text_frame.text
                if notes.strip():
                    texts.append(f"Notes: {notes}")
        return "\n".join(texts)
    except Exception as e:
        return f"[PPTX extraction failed: {e}]"

def produce_plan(source_path: str, extracted_text: str) -> dict:
    word_count = len(extracted_text.split())
    candidates = [
        {"title": f"Overview of {Path(source_path).stem}", "type": "Overview", "length": "60-90s", "focus": "High-level summary of key ideas"},
        {"title": "Key Technical Concepts", "type": "Technical", "length": "90s", "focus": "Core mechanisms or architecture"},
        {"title": "Business / Practical Implications", "type": "Business", "length": "60s", "focus": "Why it matters and outcomes"},
    ]
    if "policy" in extracted_text.lower() or "claim" in extracted_text.lower():
        candidates.append({"title": "How Decisions Are Made", "type": "How-it-works", "length": "60-90s", "focus": "End-to-end flow"})
    return {
        "source": source_path,
        "extracted_word_count": word_count,
        "candidate_videos": candidates[:4],
        "notes": "Plan generated by ingestion stub. Review and refine before script generation. Works for PDF or PPTX."
    }

def main():
    if len(sys.argv) < 2:
        print("Usage: python ingest_stub.py <file.pdf|file.pptx>")
        sys.exit(1)
    path = Path(sys.argv[1])
    if not path.exists():
        print(f"File not found: {path}")
        sys.exit(1)
    suffix = path.suffix.lower()
    if suffix == ".pdf":
        text = extract_text_pdf(path)
    elif suffix in (".pptx", ".ppt"):
        text = extract_text_pptx(path)
    else:
        text = path.read_text(errors="ignore")
    plan = produce_plan(str(path), text)
    out = path.with_suffix(".plan.json")
    out.write_text(json.dumps(plan, indent=2))
    print(f"Wrote candidate plan to {out}")
    print(json.dumps(plan, indent=2))

if __name__ == "__main__":
    main()
